"""Incident reports (Markdown + JSON) built only from already-validated structured data."""
from __future__ import annotations

from datetime import datetime, timezone


def _now():
    return datetime.now(timezone.utc).isoformat()


def generate_json_report(inc: dict) -> dict:
    return {"incident_id": inc["incident_id"], "title": inc["title"], "generated_at": _now(),
            "severity": inc["severity"], "confidence": inc["confidence"], "risk_score": inc.get("risk_score"),
            "status": inc["status"], "affected_entities": inc.get("entities", {}),
            "timeline": inc.get("timeline", []), "attack_chain": inc.get("attack_chain", []),
            "mitre_attck": inc.get("mitre_techniques", []), "evidence_event_ids": inc.get("evidence", []),
            "alert_ids": inc.get("alert_ids", []), "ai_investigation": inc.get("investigation"),
            "recommended_actions": inc.get("recommendations", []),
            "response_actions": inc.get("response_actions", []),
            "note": "All response actions are SIMULATED; no real system was modified."}


def generate_markdown_report(inc: dict) -> str:
    inv = inc.get("investigation") or {}
    L = [f"# Incident Report: {inc['incident_id']}", "", f"**{inc['title']}**", "",
         f"- **Severity:** {inc['severity'].upper()}", f"- **Confidence:** {inc['confidence']:.0%}"]
    if inc.get("risk_score") is not None:
        L.append(f"- **Risk Score:** {inc['risk_score']}/100")
    L += [f"- **Status:** {inc['status']}", f"- **Generated:** {_now()}", "",
          "## Executive Summary", inv.get("incident_summary", "_No AI investigation available._"), ""]
    if inc.get("entities"):
        L.append("## Affected Entities")
        L += [f"- **{k}:** {', '.join(v)}" for k, v in inc["entities"].items()] + [""]
    L.append("## Timeline")
    L += ([f"- `{t['timestamp']}` {t['description']} (evidence: `{t['event_id']}`)" for t in inc["timeline"]]
          if inc.get("timeline") else ["_No timeline events._"]) + [""]
    L += ["## Attack Chain", " -> ".join(inc["attack_chain"]) if inc.get("attack_chain")
          else "_Single-stage / not applicable._", "", "## MITRE ATT&CK Mapping"]
    if inc.get("mitre_techniques"):
        L += ["| Technique | Name | Status | Confidence | Evidence |", "|---|---|---|---|---|"]
        L += [f"| {m['technique_id']} | {m['technique_name']} | {m['status']} | {m['confidence']:.2f} | "
              f"{', '.join(m['evidence'])} |" for m in inc["mitre_techniques"]]
    else:
        L.append("_No techniques mapped._")
    L += ["", "## Evidence", ", ".join(inc.get("evidence", [])) or "_None._", "", "## AI Investigation"]
    if inv:
        L += [f"**Attack sequence:**\n\n{inv.get('attack_sequence', '')}\n",
              f"**Severity explanation:** {inv.get('severity_explanation', '')}\n",
              f"**Alternative explanation (could this be benign?):** {inv.get('alternative_explanation', '')}\n",
              "**Missing evidence / uncertainty:**"]
        L += [f"- {m}" for m in inv.get("missing_evidence", [])]
        L += ["", "**Recommended next investigation steps:**"]
        L += [f"- {s}" for s in inv.get("recommended_next_steps", [])]
    else:
        L.append("_Not yet investigated._")
    L += ["", "## Recommended Actions"]
    if inc.get("recommendations"):
        L += ["| Priority | Action | Reason | Evidence |", "|---|---|---|---|"]
        L += [f"| {r['priority']} | {r['action']} | {r['reason']} | {', '.join(r['evidence'])} |"
              for r in inc["recommendations"]]
    else:
        L.append("_No recommendations generated._")
    L += ["", "## Response Simulation"]
    acts = inc.get("response_actions", [])
    L += ([f"- **{a['action_type']}** on `{a['target']}` -- status: {a['status']}, decided by "
           f"{a.get('approved_by') or 'n/a'}. {a.get('result', '')}" for a in acts]
          if acts else ["_No response actions taken (none approved)._"])
    L += ["", "---", "_Generated by CYBER-SOC AGENT. AI narrative sections are evidence-grounded summaries of "
          "the structured data above, not independent findings. All response actions are SIMULATED._"]
    return "\n".join(L)
